#!/usr/bin/env python3
"""Build a starter-repo ZIP for a student's portfolio project.

Reads a JSON config from stdin describing the student / project and writes the
resulting ZIP to stdout. Pure stdlib — no external deps.

Input JSON shape:
{
  "student": str,
  "trackKey": str,           # e.g. "ai-ml-engineer"
  "trackName": str,          # e.g. "AI/ML Engineer"
  "projectTitle": str,       # e.g. "Tactical Scout AI"
  "projectGoal": str,
  "features": [str],
  "techStack": [str],
  "milestones": [{"milestone": str, "dueWeek": int}],
  "salaryEntry": str,
  "salaryMid": str,
}
"""
import io
import json
import sys
import zipfile
from datetime import datetime, timezone


def file_text(path: str, body: str) -> tuple[str, str]:
    return path, body


def build_files(spec: dict) -> list[tuple[str, str]]:
    student = spec.get("student") or "Student"
    track_key = spec.get("trackKey") or "ai-ml-engineer"
    track_name = spec.get("trackName") or "AI Track"
    project_title = spec.get("projectTitle") or "Starter Project"
    project_goal = spec.get("projectGoal") or "Define your objective before you ship."
    features = spec.get("features") or []
    tech_stack = spec.get("techStack") or []
    milestones = spec.get("milestones") or []
    salary_entry = spec.get("salaryEntry") or "TBD"
    salary_mid = spec.get("salaryMid") or "TBD"

    safe_title = (
        project_title.lower()
        .replace(" ", "-")
        .replace("/", "-")
        .replace(":", "")
        .replace("&", "and")
        .replace(",", "")
    )
    safe_track = track_key.replace("_", "-")
    slug = f"{safe_track}-{safe_title}"

    files: list[tuple[str, str]] = []

    # README
    readme = f"""# {project_title}

> Built by **{student}** for the **{track_name}** track.
> Generated by CareerDNA on {datetime.now(timezone.utc).strftime('%Y-%m-%d')}.

## Why this project

{project_goal}

## The build

Each week has a concrete deliverable that matches a real job-skill signal:

"""
    if milestones:
        for m in milestones:
            week = m.get("dueWeek", "?")
            label = m.get("milestone", "")
            readme += f"- **Week {week}** — {label}\n"
    readme += f"""
## What's in the box

```
{slug}/
├── README.md
├── package.json
├── docs/architecture.md
├── docs/careerfit.md
├── src/index.{'py' if any('python' in t.lower() or 'fastapi' in t.lower() or 'pytorch' in t.lower() for t in tech_stack) else 'ts'}
└── data/sample.json    # seed dataset
```

## Tech stack

"""
    if tech_stack:
        for tech in tech_stack:
            readme += f"- `{tech}`\n"
    readme += f"""
## Career pay envelope (use in applications)

- Entry: {salary_entry}
- Mid:    {salary_mid}

> Numbers are illustrative — research local market before quoting.

## Next steps

1. `bun install` (or `npm install`).
2. Open `src/index.{'py' if any('python' in t.lower() for t in tech_stack) else 'ts'}` and start with Week 1's milestone.
3. Push weekly. The README becomes your portfolio link.
"""
    files.append(file_text(f"{slug}/README.md", readme))

    # package.json — uniform across tracks; the student edits stack-specific bits themselves
    is_py = any("python" in t.lower() or "fastapi" in t.lower() or "pytorch" in t.lower() for t in tech_stack)
    pkg = {
        "name": slug,
        "version": "0.1.0",
        "private": True,
        "description": project_goal[:140],
        "scripts": {
            "dev": "bun run src/index.ts" if not is_py else "python -m src.index",
            "build": "echo 'edit scripts for your stack'",
            "test": "bun test" if not is_py else "pytest",
        } if not is_py else {
            "dev": "uvicorn src.index:app --reload",
            "test": "pytest",
        },
        "main": "src/index.ts" if not is_py else "src/index.py",
        "dependencies": {},
        "devDependencies": {},
        "license": "MIT",
    }
    files.append(file_text(f"{slug}/package.json", json.dumps(pkg, indent=2)))

    # Source skeleton
    if is_py:
        src = '''"""Starter entry — replace with your Week 1 deliverable."""
from fastapi import FastAPI
from datetime import datetime, timezone

app = FastAPI(title="CareerDNA Starter")


@app.get("/")
def root():
    return {
        "service": "CareerDNA starter",
        "generated_by": "CareerDNA · Qloo taste graph",
        "week": 1,
        "started": datetime.now(timezone.utc).isoformat(),
    }


if __name__ == "__main__":
    import uvicorn
    uvicorn.run(app, host="0.0.0.0", port=8000)
'''
    else:
        src = '''// Starter entry — replace with your Week 1 deliverable.
import { serve } from "bun";

serve({
  port: 3000,
  routes: {
    "/": () =>
      Response.json({
        service: "CareerDNA starter",
        generated_by: "CareerDNA · Qloo taste graph",
        week: 1,
        started: new Date().toISOString(),
      }),
  },
});
'''
    files.append(file_text(f"{slug}/src/index.{"py" if is_py else "ts"}", src))

    # Sample data
    sample = {
        "profile": {
            "student": student,
            "track": track_name,
        },
        "milestones_weeks": [m.get("dueWeek", 0) for m in milestones],
        "tech_stack": tech_stack,
        "features": features,
    }
    files.append(file_text(f"{slug}/data/sample.json", json.dumps(sample, indent=2)))

    # Architecture doc
    arch = f"""# Architecture

> Why each piece exists and what job it does in the **{track_name}** world.

## Components

```
       ┌────────────────┐   ┌────────────────┐
       │   Data Source  │ → │  Local Cache   │
       └────────────────┘   └────────────────┘
              ↓                     ↓
       ┌────────────────┐   ┌────────────────┐
       │ Domain Logic   │ ← │ Index / Vector │
       └────────────────┘   └────────────────┘
              ↓
       ┌────────────────┐
       │  HTTP Service  │  ← the part you'll deploy
       └────────────────┘
```

## Why this shape

- **Data Source** — the things you can already reach (free APIs, public datasets, your own exports).
- **Local Cache** — Week 1 should never call the network; cache hot data.
- **Domain Logic** — the reason a recruiter screenshots your repo.
- **Index / Vector** — only when you actually need retrieval (don't pre-build it).
- **HTTP Service** — the part the world sees. Ship this even when Weeks 1–3 are still rough.
"""
    files.append(file_text(f"{slug}/docs/architecture.md", arch))

    # Careerfit doc — talks to the parent hackathon story
    careerfit = f"""# Why this project fits the {track_name} track

> Written for your future self, your college admissions essay, or a recruiter
> who asked "tell me about a project".

## Raw signal (what you actually love)

Your career fit is grounded in cultural taste, which means you already have
real hours in this domain. The project above is a way to convert those hours
into something a hiring manager can verify.

## What's the proof of work

After 4 weeks, push this repo with:

- A working local service (Week 1 deliverable).
- A documented dataset / pipeline (Week 2 deliverable).
- A readme that explains *what* and *why* in plain English.

That's a portfolio that wins interviews.
"""
    files.append(file_text(f"{slug}/docs/careerfit.md", careerfit))

    # License
    lic = f"""MIT License

Copyright (c) {datetime.now(timezone.utc).year} {student}

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in
all copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT.
"""
    files.append(file_text(f"{slug}/LICENSE", lic))

    return files


def main() -> int:
    spec = json.loads(sys.stdin.read() or "{}")
    files = build_files(spec)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        for path, body in files:
            zi = zipfile.ZipInfo(path)
            zi.date_time = (2026, 1, 1, 12, 0, 0)
            zi.compress_type = zipfile.ZIP_DEFLATED
            zf.writestr(zi, body)
    sys.stdout.buffer.write(buf.getvalue())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
